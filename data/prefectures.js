// IDで都道府県を取得
function getPrefectureById(id) {
  return PREFECTURES.find(p => p.id === id) || null;
}

// 名前で都道府県を取得
function getPrefectureByName(name) {
  return PREFECTURES.find(p => p.name === name) || null;
}

// 地方でフィルタ
function getPrefecturesByRegion(region) {
  if (region === 'all') return PREFECTURES;
  return PREFECTURES.filter(p => p.region === region);
}
